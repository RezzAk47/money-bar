#!/usr/bin/env python3
"""Builds THIRD-PARTY-LICENSES.txt: the full licence text of every Rust crate compiled into the app and of every npm runtime
package, grouped so that each distinct text appears once with the list of packages that carry it. Python 3 standard library only.

Usage (from anywhere):  python3 scripts/gen-licenses.py [--check]

Rust crates: the union over the release targets of `cargo metadata --locked --filter-platform <target>`, following normal and build
dependency edges from the app crate (the same rule THIRD-PARTY-NOTICES.md states). Each crate's LICENSE*/LICENCE*/COPYING*/UNLICENSE*/
NOTICE* files are read from its source directory (found through the manifest_path, in ~/.cargo/registry), so a crate under an
SPDX "A OR B" expression contributes every licence file it ships. npm: the runtime `dependencies` of package.json and what they
depend on, read from node_modules. Needs the crates downloaded (run `cargo fetch --locked` or any build first).
--check exits 1 when the committed file differs from what would be generated.
"""
import json
import os
import re
import subprocess
import sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAURI = os.path.join(ROOT, "src-tauri")
OUT = os.path.join(ROOT, "THIRD-PARTY-LICENSES.txt")
TARGETS = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "x86_64-pc-windows-msvc",
    "x86_64-unknown-linux-gnu",
]
LICENCE_FILE = re.compile(r"^(licen[cs]e|copying|unlicen[cs]e|notice)([-_. ].*)?$", re.I)


def cargo_crates():
    """{(name, version): (spdx, source_dir, declared_license_file)} for the union of all targets."""
    found = {}
    for target in TARGETS:
        raw = subprocess.run(
            ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target],
            cwd=TAURI, check=True, capture_output=True, text=True,
        ).stdout
        meta = json.loads(raw)
        pkgs = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = meta["resolve"]["root"]
        seen, todo = set(), [root]
        while todo:
            i = todo.pop()
            if i in seen:
                continue
            seen.add(i)
            for d in nodes[i]["deps"]:
                kinds = {k.get("kind") for k in d["dep_kinds"]}
                if kinds & {None, "build"}:  # normal or build edge; dev-only edges are skipped
                    todo.append(d["pkg"])
        for i in seen:
            if i == root:
                continue
            p = pkgs[i]
            found[(p["name"], p["version"])] = (
                p.get("license") or "", os.path.dirname(p["manifest_path"]), p.get("license_file"),
            )
    return found


def licence_files(d, declared):
    names = sorted(n for n in os.listdir(d) if os.path.isfile(os.path.join(d, n)) and LICENCE_FILE.match(n))
    if declared and declared not in names and os.path.isfile(os.path.join(d, declared)):
        names.append(declared)
    return names


def read(path):
    with open(path, "rb") as f:
        return f.read().decode("utf-8", "replace").replace("\r\n", "\n").strip()


def npm_packages():
    with open(os.path.join(ROOT, "package.json"), encoding="utf-8") as f:
        top = json.load(f).get("dependencies", {})
    out, todo = {}, list(top)
    while todo:
        name = todo.pop()
        d = os.path.join(ROOT, "node_modules", *name.split("/"))
        pj = os.path.join(d, "package.json")
        if name in out or not os.path.isfile(pj):
            continue
        with open(pj, encoding="utf-8") as f:
            j = json.load(f)
        lic = j.get("license") or ""
        if not isinstance(lic, str):
            lic = str(lic)
        out[name] = (j.get("version", "?"), lic, d)
        todo.extend(j.get("dependencies", {}))
    return out


def build():
    groups = OrderedDict()  # text -> {"pkgs": set, "files": set}
    missing = []

    def add(label, spdx, d, declared):
        names = licence_files(d, declared)
        if not names:
            missing.append(f"{label} ({spdx or 'no licence declared'})")
        for n in names:
            g = groups.setdefault(read(os.path.join(d, n)), {"pkgs": set(), "files": set()})
            g["pkgs"].add(f"{label} [{spdx}]" if spdx else label)
            g["files"].add(n)

    crates = cargo_crates()
    for (name, ver), (spdx, d, declared) in sorted(crates.items()):
        add(f"{name} {ver}", spdx, d, declared)
    npm = npm_packages()
    for name, (ver, spdx, d) in sorted(npm.items()):
        add(f"npm:{name} {ver}", spdx, d, None)

    lines = [
        "THIRD-PARTY LICENCES for Money Bar",
        "",
        "Generated by scripts/gen-licenses.py; do not edit by hand. Money Bar itself is under the PolyForm Noncommercial License 1.0.0 (see LICENSE).",
        f"Contents: the licence files shipped by {len(crates)} Rust crates (the union over {', '.join(TARGETS)}) and "
        f"{len(npm)} npm runtime packages.",
        "Where a package is offered under an SPDX choice (for example MIT OR Apache-2.0), every licence file it ships is included,",
        "and you may use it under any of them. Identical texts are printed once with the list of packages that carry them.",
        "The package lists are in THIRD-PARTY-NOTICES.md; this file is not legal advice.",
        "",
    ]
    ordered = sorted(groups.items(), key=lambda kv: (-len(kv[1]["pkgs"]), sorted(kv[1]["pkgs"])[0]))
    for n, (text, g) in enumerate(ordered, 1):
        lines += ["=" * 100, f"LICENCE TEXT {n} of {len(ordered)} (file name(s): {', '.join(sorted(g['files']))})",
                  f"Used by {len(g['pkgs'])} package(s):"]
        lines += ["  " + p for p in sorted(g["pkgs"])]
        lines += ["-" * 100, text, ""]
    if missing:
        lines += ["=" * 100, "PACKAGES WITHOUT A LICENCE FILE IN THEIR SOURCE (the declared SPDX licence applies; see the package's home page)",
                  *["  " + m for m in sorted(missing)], ""]
    return "\n".join(lines), len(crates), len(npm), len(ordered), missing


def main():
    text, nc, nn, nt, missing = build()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if old == text else 1)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{OUT}: {nc} crates, {nn} npm packages, {nt} distinct texts, {len(missing)} without a licence file, {len(text)//1024} KiB")
    for m in missing:
        print("  no licence file:", m)


if __name__ == "__main__":
    main()
